// Pulls Delikacia's public menu (expz.menu) into the demo's second restaurant.
//   npx tsx scripts/expz/sync.ts [--refresh-photos]
// Writes supabase/seed/restaurants/delikaciaMenu.ts and public/demo-photos/delikacia/{id}.webp. Training fields
// (anchor, sales phrase, fact) start empty. Sections are placed by categories.ts; an unknown one stops the sync.
import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { expzMenuSchema, parseExpzMenu } from '../../supabase/seed/expzParse';
import { SYNC_HEADERS, savePhoto } from '../lib/photos';
import { DELIKACIA_PLACEMENT } from './categories';

const RESTAURANT = 'd1f5a84a-6480-4d4f-ac8a-b21a9fa47ad4';
// The page (expz.menu/<id>) is a JS app; its API needs a browser id, but the static cache it reads first is public.
const MENU_URL = `https://static.shaketopay.com.ua/menu/prod/cache/menu/${RESTAURANT}/uk/menu.json`;
const PREFIX = 'delikacia';
const PHOTO_DIR = `public/demo-photos/${PREFIX}`;
const MANIFEST = 'supabase/seed/restaurants/delikaciaMenu.ts';
// «До чаю: молоко, мед, лимон» is an add-on listed among the teas
const NOT_A_DISH = /^до чаю/i;

async function main() {
  const refresh = process.argv.includes('--refresh-photos');
  const res = await fetch(MENU_URL, { headers: SYNC_HEADERS });
  if (!res.ok) throw new Error(`${MENU_URL}: HTTP ${res.status}`);
  const menu = expzMenuSchema.parse(await res.json());
  const { items, unplaced } = parseExpzMenu(menu, DELIKACIA_PLACEMENT, PREFIX, NOT_A_DISH);
  if (unplaced.length) {
    throw new Error(
      `Menu sections with no place in the app, add them to categories.ts: ${unplaced.join(', ')}`,
    );
  }

  await mkdir(PHOTO_DIR, { recursive: true });
  const photoIds: string[] = [];
  for (const { photoUrl, id } of items) {
    if (!photoUrl) continue;
    const file = `${PHOTO_DIR}/${id}.webp`;
    if (refresh || !existsSync(file)) await savePhoto(photoUrl, file);
    photoIds.push(id);
  }

  const seedItems = items.map((item) => {
    const copy = { ...item };
    delete copy.photoUrl;
    return copy;
  });
  const today = new Date().toISOString().slice(0, 10);
  await writeFile(
    MANIFEST,
    `// Generated by scripts/expz/sync.ts from https://expz.menu/${RESTAURANT} — do not edit by hand.\n` +
      `// The demo's second restaurant (supabase/seed/restaurants.ts). Photos: public/demo-photos/${PREFIX}/{id}.webp.\n` +
      `import type { SeedMenuItem } from '../../../src/data/types';\n\n` +
      `export const DELIKACIA_SYNCED_AT = '${today}';\n\n` +
      `/** Items with the venue's own photo. */\n` +
      `export const DELIKACIA_PHOTO_IDS: string[] = ${JSON.stringify(photoIds, null, 2)};\n\n` +
      `export const DELIKACIA_ITEMS: SeedMenuItem[] = ${JSON.stringify(seedItems, null, 2)};\n`,
  );
  console.log(`${items.length} items (${photoIds.length} with photos) → ${MANIFEST}`);
}

await main();
